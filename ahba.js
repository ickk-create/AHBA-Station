/* =========================
   GET VALUE
========================= */

function getValue(obj, path) {

  return path
    .split(".")
    .reduce(
      (value, key) => value?.[key],
      obj
    ) ?? path;

}


/* =========================
   LANGUAGE
========================= */

function applyLanguage(lang) {

  if (!translations[lang]) {
    lang = "ja";
  }

  const t = translations[lang];

  document.documentElement.lang = lang;


  /* TEXT */

  document
    .querySelectorAll("[data-i18n]")
    .forEach(el => {

      el.textContent =
        getValue(
          t,
          el.dataset.i18n
        );

    });


  /* HTML */

  document
    .querySelectorAll("[data-i18n-html]")
    .forEach(el => {

      el.innerHTML =
        getValue(
          t,
          el.dataset.i18nHtml
        );

    });


  /* BUTTON */

  document
    .querySelectorAll("[data-lang]")
    .forEach(button => {

      button.classList.toggle(
        "active",
        button.dataset.lang === lang
      );

    });


  /* SAVE */

  localStorage.setItem(
    "asiaHCBBLanguage",
    lang
  );


  /* TITLE */

  if (lang === "ja") {

    document.title =
      "ABOUT AHBA | Asia HCBB Baseball Alliance";

  }

  else if (lang === "ko") {

    document.title =
      "AHBA 소개 | Asia HCBB Baseball Alliance";

  }

  else if (lang === "zh") {

    document.title =
      "关于 AHBA | Asia HCBB Baseball Alliance";

  }

  else {

    document.title =
      "ABOUT AHBA | Asia HCBB Baseball Alliance";

  }


  /* DISCORD */

  const discord =
    document.querySelector(
      ".discord .button"
    );

  if (discord) {

    discord.href =
      AHBA_DISCORD_URL;

  }

}


/* =========================
   START
========================= */

document.addEventListener(
  "DOMContentLoaded",
  () => {

    document
      .querySelectorAll("[data-lang]")
      .forEach(button => {

        button.addEventListener(
          "click",
          () => {

            applyLanguage(
              button.dataset.lang
            );

          }
        );

      });


    applyLanguage(
      localStorage.getItem(
        "asiaHCBBLanguage"
      ) || "ja"
    );

  }
);
